let current = 'en';

/** @param {'en'|'ta'} lang */
export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'en';
  document.documentElement.lang = current;
  return current;
}

export const getLanguage = () => current;

/**
 * Look up a string by dotted key, with {placeholders}.
 * @param {string} key e.g. "category.good"
 * @param {Record<string, string|number>} [params]
 * @returns {string}
 */
export function t(key, params = {}) {
  const lookup = (lang) =>
    key.split('.').reduce((node, part) => (node ? node[part] : undefined), STRINGS[lang]);
  const value = lookup(current) ?? lookup('en') ?? key;
  return String(value).replace(/\{(\w+)\}/g, (_, name) =>
    name in params ? String(params[name]) : '',
  );
}

/** Apply translations to every element that declares data-i18n* attributes. */
export function translateDocument(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}
